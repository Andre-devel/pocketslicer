package io.github.andredevel.slicer.send

import android.graphics.BitmapFactory
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class GcodeInfoTest {
    /** PNG 1x1 em base64, dividido em linhas como o Orca escreve. */
    private val png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8DwHwAFBQIAX8jx0gAAAABJRU5ErkJggg=="

    private fun block(size: String, data: String) =
        "; thumbnail begin $size ${data.length}\n" + data.chunked(78).joinToString("") { "; $it\n" } + "; thumbnail end\n"

    @Test
    fun readsLargestThumbnailUpToLimitAndFooterOfOrca() {
        val head = "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n; HEADER_BLOCK_END\n\n" +
            block("96x96", png) + "\n" + block("300x300", png) + block("900x900", "AAAA")
        val tail = """
            G1 X10 Y10
            ; EXECUTABLE_BLOCK_END
            ; filament used [mm] = 2042.80, 0.00, 1554.91, 645.27
            ; filament used [g] = 6.09, 0.00, 4.64, 1.92
            ; total filament used [g] = 12.65
            ; estimated printing time (normal mode) = 1d 2h 40m 42s
            ; CONFIG_BLOCK_START
            ; filament_colour = #ff0000;#ffffff;#0000ff
            ; filament_type = PLA;PETG;PLA;PLA
            ; CONFIG_BLOCK_END
        """.trimIndent()
        val info = GcodeInfo.parse(head, tail)
        assertNotNull(info.thumbnail)
        val thumbnail = info.thumbnail!!
        assertEquals(1, BitmapFactory.decodeByteArray(thumbnail, 0, thumbnail.size).width)
        assertEquals(86_400L + 2 * 3_600 + 40 * 60 + 42, info.seconds)
        assertEquals(12.65, info.grams!!, 1e-9)
        assertEquals(
            listOf(GcodeFilament(0, "#FF0000", "PLA", 6.09), GcodeFilament(2, "#0000FF", "PLA", 4.64), GcodeFilament(3, null, "PLA", 1.92)),
            info.filaments,
        )
    }

    @Test
    fun thumbnailCutByTheReadIsSkippedAndOtherSlicersGiveNothing() {
        val head = "; thumbnail begin 300x300 5000\n; iVBORw0KGgoAAAANSUhEUgAA"
        val info = GcodeInfo.parse(head, "; generated by PrusaSlicer\nG1 X0\n")
        assertNull(info.thumbnail)
        assertNull(info.seconds)
        assertNull(info.grams)
        assertEquals(emptyList<GcodeFilament>(), info.filaments)
    }
}
